local test = require("test")
local time = require("time")

test.case("time.now returns epoch seconds", function()
   local value = time.now()
   test.equal(type(value), "number")
   test.truthy(value > 0)
end)

test.case("time.monotonic returns monotonic seconds", function()
   local first = time.monotonic()
   local second = time.monotonic()
   test.equal(type(first), "number")
   test.equal(type(second), "number")
   test.truthy(second >= first)
end)
